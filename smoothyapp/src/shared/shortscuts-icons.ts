/** The icon a key shows: the user's choice, otherwise one guessed from its name. */
export function resolveShortsCutIcon(value: { label?: string; kind?: string; target?: string; icon?: string }): string {
  if (isShortsCutIcon(value.icon)) return value.icon;
  const text = `${value.label || ''} ${value.target || ''}`.trim().toLowerCase();
  const kind = value.kind || '';
  if (kind === 'folder') return 'folder';
  if (kind === 'multi') return 'multi';
  if (kind === 'audio-effect') {
    for (const rule of AUDIO_RULES) if (rule.pattern.test(text)) return rule.icon;
    return 'audio';
  }
  if (kind === 'audio-transition') return /power|exponential/i.test(text) ? 'out' : 'fade';
  if (kind === 'video-transition') {
    if (/dissolve|fade|dip|film/i.test(text)) return 'fade';
    if (/wipe|iris|page|clock/i.test(text)) return 'wipe';
    if (/slide|push|swipe|split/i.test(text)) return 'swap';
    if (/zoom|scale/i.test(text)) return 'zoom';
    return 'transition';
  }
  for (const rule of EFFECT_RULES) if (rule.pattern.test(text)) return rule.icon;
  return kind === 'preset' ? 'bookmark' : 'sparkle';
}

export function shortsCutIconSvg(icon: string, size = 20): string {
  const inner = SHORTSCUT_ICONS[icon] || SHORTSCUT_ICONS.sparkle;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 256 256" fill="currentColor" aria-hidden="true">${inner}</svg>`;
}
